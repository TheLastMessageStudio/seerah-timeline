/// Traduit une clé dans la langue courante, avec repli sur le français.
String tr(String key, [Map<String, Object>? args]) {
  var s = _t[Strings.lang]?[key] ?? _t['fr']![key] ?? key;
  args?.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

