/// All user-facing text. English (`_en`) and French (`_fr`).
/// A missing French key falls back to English.
String _lang = 'en';

void toggleLanguage() => _lang = _lang == 'en' ? 'fr' : 'en';
void setLanguage(String code) => _lang = code;
String get currentLanguage => _lang;

String tr(String key, [Map<String, Object?> args = const {}]) {
  var s = (_lang == 'fr' ? _fr[key] : null) ?? _en[key] ?? key;
  args.forEach((k, v) {
    s = s.replaceAll('{$k}', '$v');
  });
  return s;
}

